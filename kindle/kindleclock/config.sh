# Настройки часов. После правки перезапустите часы (Home, затем Shift, C, L).

# Адрес Kindle Hub на ПК в домашней сети. Пусто = работать без ПК.
HUB_URL="http://192.168.0.2:8765"

# 1 = сверять время автоматически: с ПК, а если он выключен, через интернет
AUTO_SYNC=1
# Как часто сверять время, в минутах
SYNC_EVERY_MIN=60
# 1 = если ПК недоступен, брать время из интернета (нужен Wi-Fi)
INTERNET_SYNC=1
# Часовой пояс для сверки через интернет, часов от UTC. При связи с ПК обновляется сам.
CLOCK_UTC_OFFSET_HOURS=3

# Ориентация при первом запуске: portrait, landscape или landscape_flip.
# Клавиша R в часах переключает её и запоминает выбор.
ORIENTATION=portrait
# Стрелки джойстика поворачиваются вместе с экраном. Если в горизонтальном режиме
# они работают «не в ту сторону», поставьте 1.
ARROWS_FLIP=0

# 1 = 24-часовой формат, 0 = 12-часовой
CLOCK_24H=1

# 1 = белый текст на чёрном фоне
NIGHT_MODE=0

# Раз в сколько минут делать полное обновление экрана с миганием (убирает «следы» e-ink)
FULL_REFRESH_EVERY=30

# 1 = показывать заряд батареи внизу
SHOW_BATTERY=1

# Размер цифр времени в пикселях без ПК: вертикально (до ~215) и горизонтально (до ~290)
TIME_PX=210
TIME_PX_LANDSCAPE=270
